"""The power-on sound (cf_fx.c cf_boot_mix) from a WAV file into a C header.

  tools/gen_boot_sound.py OUT.h [WAV]

WAV: default assets/sounds/boot.wav; 16-bit PCM at 44.1 kHz (the unit's rate), mono or stereo. Its samples are kept as
they are (no trimming, no gain): each channel IMA ADPCM (4 bit, eng_sample.c's decoder), played at its own level.
No WAV: CF_BOOT_SND_N 0, and the firmware plays its own bells instead.
"""
import array
import sys
import wave
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sampleio import ima_encode  # noqa: E402

SRC = Path(__file__).resolve().parents[1]
FS = 44100


def c_bytes(name, data):
    rows = [", ".join(str(b) for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    return [f"static const uint8_t {name}[{len(data)}] = {{"] + [f"    {r}," for r in rows] + ["};"]


def main(out, src=None):
    wav = Path(src) if src else SRC / "assets" / "sounds" / "boot.wav"
    lines = ["/* generated by tools/gen_boot_sound.py: the power-on sound, IMA ADPCM per channel */", "#pragma once"]
    if not wav.exists():
        lines.append("#define CF_BOOT_SND_N 0u")
        Path(out).write_text("\n".join(lines) + "\n")
        print("boot sound: none (the bells)")
        return
    w = wave.open(str(wav))
    nch, rate, width, n = w.getnchannels(), w.getframerate(), w.getsampwidth(), w.getnframes()
    if width != 2 or rate != FS or nch not in (1, 2):
        raise SystemExit(f"{wav}: needs 16-bit PCM at {FS} Hz, mono or stereo (it is {width * 8}-bit, {rate} Hz, {nch} ch)")
    pcm = array.array("h", w.readframes(n))
    if sys.byteorder == "big":
        pcm.byteswap()
    chans = [list(pcm[c::nch]) for c in range(nch)]
    if nch == 1:
        chans.append(chans[0])
    left, _ = ima_encode(chans[0], 0)
    right, _ = ima_encode(chans[1], 0) if nch == 2 else (left, None)
    lines.append(f"#define CF_BOOT_SND_N {n}u   /* frames, {n / FS:.2f} s, from {wav.name} */")
    lines += c_bytes("CF_BOOT_SND_L", left)
    if nch == 2:
        lines += c_bytes("CF_BOOT_SND_R", right)
    else:
        lines.append("#define CF_BOOT_SND_R CF_BOOT_SND_L")
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"boot sound: {wav.name}, {n / FS:.2f} s, {nch} ch, {len(left) * (1 if nch == 1 else 2)} B ADPCM")


if __name__ == "__main__":
    main(*sys.argv[1:3])
