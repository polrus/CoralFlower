"""The intro's title, "Sornyak", in Pixelify Sans (SIL OFL 1.1, assets/fonts), as a C header of 1-bit letters.

    python3 tools/gen_title.py OUT.h

The word is rendered whole at 13 px, weight 500, without anti-aliasing (the font's own pixel grid at that size), then
cut into its letters at their advances, so cf_splash.c can colour each one and drop it in on its own. Each letter: its
x in the word, its width, and a 16-bit row mask per row (bit 15 = its leftmost pixel). No Raqm, no kerning.
"""
import pathlib
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT = ROOT / "assets" / "fonts" / "PixelifySans[wght].ttf"
WORD, PX, WEIGHT = "Sornyak", 13, 500


def main():
    out = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "build" / "gen" / "cf_title.h")
    font = ImageFont.truetype(str(FONT), PX, layout_engine=ImageFont.Layout.BASIC)
    font.set_variation_by_axes([WEIGHT])
    w = int(round(font.getlength(WORD))) + 4
    im = Image.new("1", (w, PX + 6), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((0, 0), WORD, font=font, fill=1)
    x0, y0, x1, y1 = im.getbbox()
    h = y1 - y0
    cuts = [int(round(font.getlength(WORD[:i]))) for i in range(len(WORD) + 1)]
    cuts[-1] = max(cuts[-1], x1)
    letters = []
    for i, ch in enumerate(WORD):
        a, b = cuts[i], cuts[i + 1]
        cols = [x for x in range(a, b) if any(im.getpixel((x, y)) for y in range(y0, y1))]
        lx, rx = min(cols), max(cols) + 1
        if rx - lx > 16:
            raise SystemExit(f"gen_title: {ch!r} is wider than 16 px")
        rows = []
        for y in range(y0, y1):
            v = 0
            for x in range(lx, rx):
                if im.getpixel((x, y)):
                    v |= 0x8000 >> (x - lx)
            rows.append(v)
        letters.append((ch, lx - x0, rx - lx, rows))
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w") as f:
        f.write("/* Generated by tools/gen_title.py - do not edit. Pixelify Sans: SIL OFL 1.1 "
                "(LICENSES/OFL-PixelifySans.txt). */\n#ifndef CF_TITLE_GEN_H\n#define CF_TITLE_GEN_H\n#include <stdint.h>\n")
        f.write(f"#define CF_TITLE_N {len(letters)}\n#define CF_TITLE_H {h}\n#define CF_TITLE_W {x1 - x0}\n")
        f.write("typedef struct { char ch; uint8_t x, w; uint16_t rows[CF_TITLE_H]; } cf_title_t;\n")
        f.write("static const cf_title_t CF_TITLE[CF_TITLE_N] = {\n")
        for ch, x, lw, rows in letters:
            f.write(f"    {{'{ch}', {x}, {lw}, {{" + ", ".join(f"0x{v:04X}" for v in rows) + "}},\n")
        f.write("};\n#endif\n")
    print(f"title: {WORD!r} {x1 - x0}x{h} px -> {out}")


if __name__ == "__main__":
    main()
